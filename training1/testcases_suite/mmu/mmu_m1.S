//    Description: 
//
//    virtual to physical address translating (instruction):
//   		   #satp = 0x8000000000070002
//   		   #L2 pte_addr= 0x70002000 pte = 0x000000001c000401 
//   		   #L1 pte_addr= 0x70001000 pte = 0x000000001c000001 
//   		   #L0 pte_addr= 0x70000000 pte = 0x00000000000000cf 
//                 #VA = 0x0 
//                 #PA = 0x0 
//
//   virtual to physical address translating (Data):
//   		   #satp = 0x8000000000070002
//   		   #L2 pte_addr= 0x70002000 pte = 0x000000001c000401 
//   		   #L1 pte_addr= 0x70001100 pte = 0x000000001c000001 
//   		   #L0 pte_addr= 0x700000d0 pte = 0x600000001c0800c9    
//                 #VA = 0x401add8 
//                 #PA = 0x70200dd8
########################################################################


# ---------------------------------------------
# Step 1: Load page table base address
# ---------------------------------------------

    la      x1, inp_data

# ---------------------------------------------
# Step 2: Configure SATP register
# MODE = 8 (Sv39)
# ---------------------------------------------

    srli    x2, x1, 12          # PPN
    li      x3, 8               # Sv39 mode
    slli    x3, x3, 60          # MODE field
    or      x2, x2, x3

    csrw    satp, x2            # Enable MMU





.section .data

inp_data:
#############################################################
.dword 0x00000000000000cf //70000000 + 8
.skip (0x700000d0 - 0x70000000 -8 )//.skip 0xC8
/*
	0x700000d0
   -0x70000000
   ------------
	0xD0
0xD0 - 8 = 0xC8
*/

.dword 0x000000001c0800c9   //0x700000d0 + 8    
############################################################# 
#----------------------------------------------------------------
#############################################################
.skip (0x70001000 - 0x700000d0 -8 )//.skip 0xF28
/*
	 0x70001000
	-0x700000d0
	------------
	 0xF30
	 0xF30 - 8 = 0xF28
*/
.dword 0x000000001c000001 //0x70001000	+ 8
#############################################################
#------------------------------------------------------------------
#############################################################
.skip (0x70001100 -0x70001000 - 8 )//.skip 0xF8
/*
	 0x70001100
	-0x70001000
	------------
	 0x100

	0x100 - 8 = 0xF8
*/
.dword 0x000000001c000001 //0x70001100           
#############################################################
#------------------------------------------------------------------
#############################################################
.skip (0x70002000 -0x70001100 - 8 )//.skip 0xEF8
/*
	 0x70002000
	-0x70001100
	------------
	 0xF00
	0xF00 - 8 = 0xEF8
*/
.dword 0x000000001c000401 //0x70002000
#############################################################
